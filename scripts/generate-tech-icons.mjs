/**
 * Regenerates `src/config/tech-icons.ts` from simple-icons.
 *
 * The paths are committed rather than imported, so nothing at runtime depends
 * on a 3,000 icon package and only the sixty shapes actually used are shipped.
 * Run it after adding to a catalog in `src/config/skills.ts`; it reads that
 * file, so anything new without an icon is reported rather than missed.
 *
 *   node scripts/generate-tech-icons.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";

import * as simpleIcons from "simple-icons";

/** Where a catalog name and the icon's own name do not agree. */
const SLUGS = {
  HTML: "html5",
  Vue: "vuedotjs",
  Rails: "rubyonrails",
  // React Native's mark is React's.
  "React Native": "react",
};

const icons = Object.values(simpleIcons).filter((icon) => icon?.title && icon?.path);
const byTitle = new Map(icons.map((icon) => [icon.title.toLowerCase(), icon]));
const bySlug = new Map(icons.map((icon) => [icon.slug, icon]));

const source = readFileSync("src/config/skills.ts", "utf8");

function catalog(name) {
  const block = source.match(new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\] as const;`));
  if (!block) throw new Error(`No ${name} catalog found in src/config/skills.ts`);
  return [...block[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]);
}

const names = [...catalog("LANGUAGES"), ...catalog("FRAMEWORKS"), ...catalog("TOOLS")];

function lookup(name) {
  if (name in SLUGS) return bySlug.get(SLUGS[name]);

  // simple-icons' own slug rules, which is how "C++" becomes "cplusplus".
  const guess = name
    .toLowerCase()
    .replace(/\+/g, "plus")
    .replace(/\./g, "dot")
    .replace(/#/g, "sharp")
    .replace(/[^a-z0-9]/g, "");

  return byTitle.get(name.toLowerCase()) ?? bySlug.get(guess);
}

const found = [];
const missing = [];

for (const name of names) {
  const icon = lookup(name);
  if (icon) found.push([name.toLowerCase(), icon.path]);
  else missing.push(name);
}

const entries = found
  .map(([key, path]) => `  ${JSON.stringify(key)}: ${JSON.stringify(path)},`)
  .join("\n");

writeFileSync(
  "src/config/tech-icons.ts",
  `/**
 * Brand marks for the skill catalogs, as bare SVG path data on a 24x24 grid.
 *
 * Generated by scripts/generate-tech-icons.mjs from simple-icons (CC0). Do not
 * edit by hand. Keyed by lowercased name, so a technology someone typed
 * themselves matches one of these when it happens to be the same thing.
 *
 * Not everything has a mark: Java, C# and SQL have no icon in the set, and
 * anything absent falls back to a monogram rather than a gap.
 */

export const TECH_ICON_PATHS: Record<string, string> = {
${entries}
};
`,
  "utf8",
);

console.log(`Wrote src/config/tech-icons.ts with ${found.length} of ${names.length} marks.`);
if (missing.length > 0) console.log(`No mark available: ${missing.join(", ")}`);
