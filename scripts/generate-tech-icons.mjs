/**
 * Regenerates `src/config/tech-icons.ts` from simple-icons.
 *
 * The paths are committed rather than imported, so nothing at runtime depends
 * on a 3,000 icon package and only the shapes actually used are shipped. Run it
 * after adding to a catalog in `src/config/skills.ts`; it reads that file, so
 * anything new without an icon is reported rather than missed.
 */

import { readFileSync, writeFileSync } from "node:fs";

import * as simpleIcons from "simple-icons";

/** Where a catalog name and the icon's own name do not agree. */
const SLUGS = {
  HTML: "html5",
  Vue: "vuedotjs",
  Rails: "rubyonrails",
  // React Native's mark is React's.
  "React Native": "react",
};

const INK = "#191817";
const CANVAS = "#eceae5";

/** A colour dark enough to read on paper, light enough to read on ink. */
const LIGHTEST_ON_CANVAS = 0.46;
const DARKEST_ON_INK = 0.62;

/** Below this there is no hue worth keeping, so the mark takes the ink colour. */
const COLOURLESS = 0.12;

function toHsl(hex) {
  const [r, g, b] = [1, 3, 5].map((at) => parseInt(hex.slice(at, at + 2), 16) / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;

  if (max === min) return { h: 0, s: 0, l };

  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h =
    max === r
      ? ((g - b) / d + (g < b ? 6 : 0)) / 6
      : max === g
        ? ((b - r) / d + 2) / 6
        : ((r - g) / d + 4) / 6;

  return { h, s, l };
}

function toHex({ h, s, l }) {
  const f = (n) => {
    const k = (n + h * 12) % 12;
    const a = s * Math.min(l, 1 - l);
    const value = l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
    return Math.round(value * 255)
      .toString(16)
      .padStart(2, "0");
  };
  return `#${f(0)}${f(8)}${f(4)}`;
}

/**
 * A brand colour, made readable on each of the two grounds.
 *
 * Published brand colours assume a white page and a logo far bigger than
 * 13 pixels. Several of these marks are pure black, which disappears on the
 * dark canvas, and a few are pale enough to disappear on the light one. Hue
 * survives; lightness is clamped to whichever side of the page it sits on.
 */
function readable(hex) {
  const { h, s, l } = toHsl(hex);
  if (s < COLOURLESS) return { light: INK, dark: CANVAS };

  return {
    light: toHex({ h, s, l: Math.min(l, LIGHTEST_ON_CANVAS) }),
    dark: toHex({ h, s, l: Math.max(l, DARKEST_ON_INK) }),
  };
}

const icons = Object.values(simpleIcons).filter((icon) => icon?.title && icon?.path);
const byTitle = new Map(icons.map((icon) => [icon.title.toLowerCase(), icon]));
const bySlug = new Map(icons.map((icon) => [icon.slug, icon]));

const source = readFileSync("src/config/skills.ts", "utf8");

function catalog(name) {
  const block = source.match(new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\] as const;`));
  if (!block) throw new Error(`No ${name} catalog found in src/config/skills.ts`);
  return [...block[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]);
}

const names = [...catalog("LANGUAGES"), ...catalog("FRAMEWORKS"), ...catalog("TOOLS")];

function lookup(name) {
  if (name in SLUGS) return bySlug.get(SLUGS[name]);

  // simple-icons' own slug rules, which is how "C++" becomes "cplusplus".
  const guess = name
    .toLowerCase()
    .replace(/\+/g, "plus")
    .replace(/\./g, "dot")
    .replace(/#/g, "sharp")
    .replace(/[^a-z0-9]/g, "");

  return byTitle.get(name.toLowerCase()) ?? bySlug.get(guess);
}

const found = [];
const missing = [];

for (const name of names) {
  const icon = lookup(name);
  if (!icon) {
    missing.push(name);
    continue;
  }

  const { light, dark } = readable(`#${icon.hex}`);
  found.push({ key: name.toLowerCase(), path: icon.path, light, dark, brand: `#${icon.hex}` });
}

const entries = found
  .map(
    (icon) =>
      `  ${JSON.stringify(icon.key)}: {\n` +
      `    light: ${JSON.stringify(icon.light)},\n` +
      `    dark: ${JSON.stringify(icon.dark)},\n` +
      `    path: ${JSON.stringify(icon.path)},\n` +
      `  },`,
  )
  .join("\n");

writeFileSync(
  "src/config/tech-icons.ts",
  `/**
 * Brand marks for the skill catalogs: SVG path data on a 24x24 grid, and the
 * brand colour adjusted to stay readable on each background.
 *
 * Generated by scripts/generate-tech-icons.mjs from simple-icons (CC0). Do not
 * edit by hand. Keyed by lowercased name, so a technology someone typed
 * themselves matches one of these when it happens to be the same thing.
 *
 * Without a mark${missing.length > 0 ? `, and shown as a monogram instead: ${missing.join(", ")}` : ": nothing"}.
 */

export interface TechIconData {
  /** For the paper background. */
  light: string;
  /** For the ink background, where several of these brands are black. */
  dark: string;
  path: string;
}

export const TECH_ICONS: Record<string, TechIconData> = {
${entries}
};
`,
  "utf8",
);

console.log(`Wrote src/config/tech-icons.ts with ${found.length} of ${names.length} marks.`);
if (missing.length > 0) console.log(`No mark available: ${missing.join(", ")}`);

// Anything the clamp moved a long way is worth eyeballing in the interface.
const shifted = found.filter((icon) => icon.light.toLowerCase() !== icon.brand.toLowerCase());
console.log(`\nAdjusted for the light background (${shifted.length}):`);
for (const icon of shifted) {
  console.log(`  ${icon.key.padEnd(16)} ${icon.brand} -> light ${icon.light}  dark ${icon.dark}`);
}
